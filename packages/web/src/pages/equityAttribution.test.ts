/**
 * **两个权益口径不能混成一个数**（2026-10-13 用户报「图表显示和实际账号对不上」）。
 *
 * ## 用户看到的（截图）
 *
 * ```
 *   指标卡「账户余额」  97.93  ·「交易盈亏」−$2.12（−2.11%）   ← 账户口径
 *   图表「本段变化」           +$8.45（+8.44%）                 ← 归属口径
 *   用户原话：「图表上显示和实际账号对不上」
 * ```
 *
 * ## 两个数都对 —— 错的是"没有说清它们是两个口径"
 *
 * ```
 *   equity         = initial_equity + Σ(本机器人已平仓净额)   ← 图表画这个
 *   account_equity = 共享钱包的真实权益                        ← 指标卡显示这个
 * ```
 * 实测 `#10`（2026-10-13）：
 * ```
 *   equity         = 108.47   （100.05 + 它的净盈亏 +8.4455）
 *   account_equity =  97.80
 *   差额           =  10.67   ← 同一个钱包上 #9/#11 的亏损
 * ```
 * 见 `db/schema.ts` 的 `M4_ATTRIBUTED_EQUITY` 迁移说明。
 *
 * ## 为什么这个测试值得写
 *
 * 这是**第二处**同类问题（第一处是"交易所账户"那一行，见 `TraderPage` 里
 * `lastKnownAccount` 的注释）。而它两次都是**静默的**：
 * ```
 *   数字没错、页面不报错、曲线也照画 —— 只有操作员会困惑
 * ```
 * 所以这里把"两个口径必须并排出现、且差额必须被归因"变成可执行的断言。
 *
 * ⚠️ **这个测试扫的是源码文本**，所以注释里的同名字串会命中 ——
 * 这是本项目踩过多次的坑（见 `testUtils/sourceText.ts`）。
 * 实际做法是**只断言"存在"，不断言"不存在"**，从根上避开那个坑。
 * 唯一那条"不存在"的断言（旧文案）指向的是**不可能出现在解释注释里的原文**。
 */
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import test from 'node:test';

const PAGE = readFileSync(new URL('./TraderPage.tsx', import.meta.url), 'utf8');

test('★★★ 权益曲线那一行必须同时给出【归属】与【账户】两个口径', () => {
  assert.ok(
    PAGE.includes('本机器人归属'),
    '★ 必须明确标出第一行是"本机器人归属"口径（否则用户默认它 = 账户余额）',
  );
  assert.ok(PAGE.includes('同期账户'), '★ 必须有"同期账户"对照行');
  assert.ok(
    PAGE.includes('同一钱包含其他机器人'),
    '★ 必须说清差额的来源是"同一钱包的其他机器人"（这才是用户困惑的答案）',
  );
});

test('★★★ 差额必须被【归因】，不能只报一个差数', () => {
  /*
   * ⚠️ "差 10.55" 本身又是一个要用户自己想的问题 ——
   * 那等于把困惑从"为什么对不上"换成了"这 10.55 是什么"。
   */
  assert.ok(
    /本机器人跑赢同账户其他机器人/.test(PAGE),
    '★ 必须把差额归因到"本机器人与同账户其他机器人的相对表现"',
  );
});

test('★★★ 账户对照行必须用【同窗口】的数据（不能拿最新值比历史段）', () => {
  /*
   * ⚠️ 这是最容易写错的地方：图表讲的是"这一段涨跌了多少"，
   * 若拿一个**不同时段**的账户数字来比，差额里会混进"时段不同"，
   * 反而更难解释。所以两端都要取自 `windowed`（同一份可见区间数据）。
   */
  assert.ok(
    /windowAccountFirst\s*=/.test(PAGE) && /windowAccountLast\s*=/.test(PAGE),
    '★ 账户口径必须同时取可见区间的【首】与【末】两端',
  );
  /* 首端必须明确取自 windowed[0]。 */
  assert.ok(
    /windowed\[0\]\?\.accountEquity/.test(PAGE),
    '★ 首端必须取自 `windowed[0].accountEquity`（与图表同一份数据）',
  );
});

test('★★★ 数据不足时【不能显示】对照行（否则会算出一个巨大的假差额）', () => {
  /*
   * ⚠️ 迁移前的旧行 `account_equity` 是回填的，而**完全没有值时它是 `0`**
   * （见 `db/schema.ts` 的 M4 取舍说明）。拿 0 去算会得出一个
   * "账户亏了 100%" 的假结论 —— 那比不显示更糟。
   */
  assert.ok(
    /hasAccountCompare/.test(PAGE),
    '★ 必须有 `hasAccountCompare` 这道门槛',
  );
  assert.ok(
    /windowAccountFirst\s*>\s*0/.test(PAGE) && /windowAccountLast\s*>\s*0/.test(PAGE),
    '★ 门槛必须含"两端都 > 0"（0 = 没有数据，不是"权益为 0"）',
  );
  assert.ok(
    /windowed\.length\s*>=\s*2/.test(PAGE),
    '★ 门槛必须含"至少 2 个快照"（1 个快照算不出变化）',
  );
});

test('★★★ 文案里不能出现"多 +$x"这种符号冗余', () => {
  /*
   * ⚠️ 我第一版写的是 `（本机器人归属比其他机器人多 {fmtUsdSigned(gap)}）`
   * —— `fmtUsdSigned` 已经带符号，于是渲染出"多 +$21.31"：
   * "多"与"+"重复。实测截图抓到的。
   */
  assert.ok(
    !/比其他机器人多\s*\{?\s*fmtUsdSigned/.test(PAGE),
    '★ 不要在带符号的数字前再写"多"',
  );
});

test('★ 第一处同类问题的注释必须还在（它解释"为什么要两个口径"）', () => {
  /*
   * `lastKnownAccount` 那段注释记录了**第一次**同类问题
   *（"交易所账户"那行显示"暂无实时读数"）。它是这个设计决策的依据，
   * 删掉之后下一个人会再问一遍"为什么要单独给账户口径"。
   */
  assert.ok(
    PAGE.includes('操作员看到 9.42、去交易所看到 7.54'),
    '★ 必须保留第一次事故的实测记录（它是"两个口径都要显示"这个决策的依据）',
  );
});
