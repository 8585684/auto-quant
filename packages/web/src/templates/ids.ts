/**
 * 模板与页面之间**靠 DOM id 约定的那几个挂载点**。
 *
 * ## 为什么单独一个文件
 *
 * 这些常量有两类使用者，而它们分处两个目录：
 *
 *   · **模板**（`templates/*`）负责把它们渲染出来 —— 侧栏、内容区、工具栏槽；
 *   · **页面**（`pages/*`、`components/*`）负责去找它们 —— 动作 portal 到哪、
 *     监听哪个容器的滚动。
 *
 * 写在任一侧都会让另一侧产生一条"反向依赖"（页面 import 模板，或者模板
 * import 页面里的东西）。放在这里，两边都只依赖一份常量，而这份常量是
 * **契约**：改了它，两边一起改；漏改一边的表现是**功能静默消失**
 * （`getElementById` 返回 null，调用方什么都不画，页面看起来完全正常）。
 *
 * ## 为什么用 `getElementById` 而不是 React Context
 *
 * 因为**跨路由**：页面是 `<Outlet />` 里被路由渲染的，模板是它的父级 ——
 * Context 走得通。真正走不通的是"页面在模板挂载之前就要拿到挂载点"这件事：
 * 页面组件的渲染先于模板的 DOM 提交，所以拿到的永远是 null。用 DOM id +
 * 一帧延迟（见 `PageActions`）是最不容易出错的形式。
 */

/**
 * 内容区滚动容器的 id。
 *
 * ⚠️ **任何模板的内容区都必须带这个 id。** `FaqPage` 的目录跟随高亮要监听
 * 它的 `scroll` 事件；找不到时它会静默返回，而页面看起来毫无异常。
 *
 * 以前那些地方靠 `querySelector('main')` 去找，而当时的元素是一个没有 id 的
 * `<div>`：查找静默失败、功能静默不工作。这个 id 就是那次事故的修复。
 */
export const MAIN_SCROLL_ID = 'main-scroll';

/**
 * 工具栏左槽（普通动作：刷新、筛选、导出）。
 *
 * 页面用 `<PageActions start={…}>` 把动作投进来。**模板可以完全不渲染它** ——
 * 那时 `PageActions` 会把同样的动作就地渲染，功能不会丢（见它的注释）。
 */
export const TOOLBAR_START_ID = 'aq-toolbar-start';

/**
 * 工具栏右槽（主操作 / 危险动作：新建、保存、删除）。
 *
 * 分两个槽而不是一个，是因为**破坏性动作必须永远在最右** —— 那件事不该由
 * 每个页面自己记得。
 */
export const TOOLBAR_END_ID = 'aq-toolbar-end';
