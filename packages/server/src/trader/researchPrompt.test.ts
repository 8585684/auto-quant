import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { test } from 'node:test';

/**
 * **调研 agent 的提示词必须要求"发布时刻"与"多来源"**（防漂移）。
 *
 * ## 为什么用"读源码 + 断言"这种测法
 *
 * `manager.ts` 是一个 2800 行的编排类，构造它需要一整套依赖
 *（DB / 交易所 / 网关 / 事件总线）—— 为一个**提示词字符串**搭那一套不划算。
 *
 * 而这条要求**必须被钉住**，因为它连接着两个模块：
 *
 * ```
 *   manager.ts 的提示词 ──产出"发布时刻/来源"──→ intel/freshness.ts 的衰减与交叉验证
 * ```
 *
 * 若提示词不再要求这些字段，`freshness.ts` 就成了**空转**：
 * `publishedAt` 只能全部填"现在"（于是永远新鲜）、
 * `sourceHost` 无从判断（于是"转载"与"独立来源"分不清）。
 * **而它不会报错** —— 那正是最危险的一类失效。
 *
 * 所以这里用最直接的方式：**断言那两句要求还在**。
 * 与 `ROLE_TIERS` 的防漂移测试同一性质：**要求可以被改，但不能被悄悄删掉。**
 */
const SRC = readFileSync(new URL('./manager.ts', import.meta.url), 'utf8');

test('★★★ 调研提示词要求"每条新闻写明发布时刻"（freshness 的输入）', () => {
  /*
   * 用户原话：
   * > 「消息面的东西**常常有时效性**，如果消息面的策略失效后，应当会及时修正、调整」
   *
   * 而 `intel/freshness.ts` 的衰减需要 `publishedAt` —— 它只能来自模型的产出。
   */
  assert.ok(
    SRC.includes('每条新闻必须写明它的【发布时刻】'),
    '★ 缺了它 → freshness 的衰减逻辑会空转（publishedAt 只能全填"现在"）',
  );
  assert.ok(
    SRC.includes('不要用"最近"这种模糊说法'),
    '★ 模糊时间无法用于衰减计算',
  );
});

test('★★★ 调研提示词要求"同一件事的多家报道列在一起"（交叉验证的输入）', () => {
  /*
   * `intel/freshness.ts` 的交叉验证按**域名去重** —— 但前提是
   * 模型把"同一件事的多家报道"放在一起，我们才能识别出
   * "这是一个来源还是多个独立来源"。
   *
   * 若不要求，模型会给一堆平铺的新闻 —— 于是"转载"会被误判成
   * "多个来源确认"（**假确认**）。
   */
  assert.ok(
    SRC.includes('同一件事若有多家媒体报道，列在同一条下面'),
    '★ 缺了它 → 交叉验证会把"转载"误判成"多来源确认"',
  );
});

test('★ 提示词仍要求"带来源链接"与"查不到就明说"（原有要求不能被覆盖掉）', () => {
  assert.ok(SRC.includes('带来源链接'), '来源链接是防幻觉的第一道闸');
  assert.ok(SRC.includes('明确说查不到'), '防"用常识填充成新闻"');
});
