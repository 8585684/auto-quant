/**
 * **两个"材料对分析师说谎"的真 BUG**（2026-10-13，线上实测）。
 *
 * ## BUG ①：系统承诺了一个它给不了的工具
 *
 * `prompt.ts` 渲染候选区块时写着：
 * ```
 *   **其余只给摘要**……而**任何一个你想深看的标的，都可以用 `get_klines`
 *   点名要完整序列**，不必它排前面。
 * ```
 * 那句话**是给单模型写的** —— 单模型（`autoTrader`）确实有工具循环
 *（`MAX_DATA_ROUNDS = 3`），它真的能调 `get_klines`。
 *
 * 而团队模式的四个分析师走**单次调用**（`AskRole` → `complete()`），
 * **没有任何工具**。它们读到那句话之后的反应（线上原文）：
 * ```
 *   market_analyst：「**我没有工具**，不能调 `get_klines`。所以我能做的分析，
 *                     严格限定在这 6 个标的上。」
 *   technical：     「**我没有任何工具，不能取数。**」
 * ```
 * **它们每轮都要花一段话去否定一个系统对它们做出的承诺。**
 *
 * ## BUG ②：标题说 14 个，实际只给 6 个
 *
 * 标题是 `# 候选标的（14 个）` + `**前 10 个给出完整指标序列**`，
 * 而分析师只收到 6 个切片 → 它读到"说有 14 个、前 10 个完整"却只看到 6 个。
 *
 * 线上实测四个分析师**每轮各写 200–400 字**解释这个矛盾：
 * ```
 *   market_analyst：「本轮材料只给了我 **6 个候选的完整指标序列**…另外 8 个
 *                     候选只有摘要。」
 *   technical：     「本轮共有 **14 个候选**，但材料只给了 **6 个完整序列**…
 *                     另外 8 个本轮我没有序列，也没有它们的最新值。」
 * ```
 * 那些字**不产生任何交易判断**，只让它们对自己的输入产生不确定。
 *
 * ## ⚠️ 这两个替换都是"对已渲染文本做定点替换"
 *
 * 与 `splitMarketContext` 的纪律一致：**不改渲染，只改这一份副本**。
 * 风险是"格式变了导致正则不中" —— 所以这里用**线上真实文本**做断言，
 * 而不是自己造的简化样本（那样会"测试通过但线上不中"）。
 */
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import test from 'node:test';

const DESK = readFileSync(new URL('./tradingDesk.ts', import.meta.url), 'utf8');

/* -------------------------------------------------------------------------- */
/*  ① 工具承诺                                                                   */
/* -------------------------------------------------------------------------- */

test('★★★ 分析师材料里那句"可以用 get_klines"必须被替换掉', () => {
  assert.ok(
    /NO_TOOL_PROMISE/.test(DESK),
    '★ 必须有 `NO_TOOL_PROMISE` 这个替换（分析师没有工具，那句承诺是假的）',
  );
  assert.ok(
    /你没有工具，看不到的序列就是拿不到的/.test(DESK),
    '★ 必须换成真实边界（"看不到的就是拿不到的"）',
  );
  assert.ok(
    /stripToolPromise\(/.test(DESK),
    '★ 替换必须真的被调用（定义了不用 = 没修）',
  );
});

test('★★★ 正则必须匹配【线上真实的那句话】（否则线上不中）', () => {
  /*
   * ⚠️ 这条是本测试文件最重要的断言：它用**线上原文**验证正则。
   * 自己造一个简化样本会让测试通过而线上不生效。
   */
  const m = /const NO_TOOL_PROMISE = (\/.*\/);/.exec(DESK);
  assert.ok(m !== null, '★ 找不到 `NO_TOOL_PROMISE` 的字面量');
  const literal = m[1] ?? '';
  /* 取出正则体（去掉首尾 `/`）。 */
  const body = literal.slice(1, literal.lastIndexOf('/'));
  const re = new RegExp(body);
  /* 线上真实文本（从 `#11` 的材料里抄的）。 */
  const online =
    '**其余只给摘要**（最新值 + 最近 5 根的走向）—— 那足够用来筛掉它们，' +
    '而**任何一个你想深看的标的，都可以用 `get_klines` 点名要完整序列**，不必它排前面。';
  assert.ok(re.test(online), `★ 正则不匹配线上原文（正则体：${body}）`);
});

/* -------------------------------------------------------------------------- */
/*  ② 标题与内容一致                                                             */
/* -------------------------------------------------------------------------- */

test('★★★ 候选标题必须被改写成"实际收到的那一份"', () => {
  assert.ok(
    /rewriteCandidateHeader/.test(DESK),
    '★ 必须有 `rewriteCandidateHeader`',
  );
  assert.ok(
    /本轮材料列出 \$\{useSlices\.length\} 个，均已给出完整指标序列/.test(DESK),
    '★ 标题必须说明"本轮列出了几个、且都是完整序列"',
  );
  assert.ok(
    /rewriteCandidateHeader\(\s*stripToolPromise\(/.test(DESK),
    '★ 两个替换都必须真的被调用（定义了不用 = 没修）',
  );
});

test('★★★ 标题正则必须匹配【线上真实的标题】', () => {
  const m = /text\.replace\(\s*(\/.*?\/),\s*`# 候选标的/.exec(DESK);
  assert.ok(m !== null, '★ 找不到标题替换的正则');
  const literal = m[1] ?? '';
  const body = literal.slice(1, literal.lastIndexOf('/'));
  const re = new RegExp(body);
  /* 线上真实标题（从 `#11` 的材料里抄的）。 */
  const online =
    '# 候选标的（14 个）\n' +
    '**前 10 个给出完整指标序列**（按由旧到新排列，最后一个值就是最新值）；' +
    '**其余只给摘要**（最新值 + 最近 5 根的走向）—— 那足够用来筛掉它们，' +
    '而**任何一个你想深看的标的，都可以用 `get_klines` 点名要完整序列**，不必它排前面。';
  assert.ok(re.test(online), `★ 正则不匹配线上标题（正则体：${body}）`);
});

/* -------------------------------------------------------------------------- */
/*  ③ 不要让它们复述边界                                                          */
/* -------------------------------------------------------------------------- */

test('★★★ 说明里不该再要求分析师"复述数据边界"（那是纯浪费）', () => {
  /*
   * ⚠️ 原来的措辞是"并明确说明这是你的数据边界" —— 于是四个分析师
   * **每一轮都各写一大段"先说数据边界"**。而那些字不产生任何交易判断。
   * 边界已经由说明写清楚了，让它们复述是浪费输出预算。
   */
  assert.ok(
    /不要在回答里复述这段边界说明/.test(DESK),
    '★ 必须明确要求"不要复述边界"',
  );
});
